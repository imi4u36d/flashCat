#!/bin/bash
# Build the native macOS client (SwiftUI + AppKit) and assemble flashCat.app.
#
# No inference runtime ships inside the bundle any more: splash, oMLX and MTPLX
# are all runtime packs, installed by the app's launch page from the pack index
# (or from an existing vendor/engines checkout during development).
#
#   INSTALL=0 ./scripts/build-native-app.sh      keep the bundle in dist/ only
#   VERSION=1.1.0 ./scripts/build-native-app.sh  override the bundle version
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="${VERSION:-1.0.0}"
BUILD_NUMBER="${BUILD_NUMBER:-1}"
INSTALL="${INSTALL:-1}"
IDENTIFIER="${IDENTIFIER:-com.zhuo.flashCat}"
# macOS 26.4 is the floor splash's native engine enforces.
MIN_MACOS="${MIN_MACOS:-26.4}"
# How the runtime packs reach `Contents/Resources/engines`. The installed app must
# carry its own copy: a symlink into the checkout breaks the moment the checkout
# moves, which is exactly what happens after `make app`. `link` is kept for the
# fast development loop (no GB-sized copy per build).
EMBED_PACKS="${EMBED_PACKS:-copy}"
OUT_DIR="${OUT_DIR:-$ROOT/dist}"
APP="$OUT_DIR/flashCat.app"
NATIVE_DIR="$ROOT/native"

command -v swift >/dev/null 2>&1 || {
    echo "error: swift toolchain not found" >&2
    exit 1
}

echo "==> Swift release build"
( cd "$NATIVE_DIR" && swift build -c release --disable-sandbox )
BINARY="$NATIVE_DIR/.build/release/flashCat"
[ -x "$BINARY" ] || {
    echo "error: swift build did not produce $BINARY" >&2
    exit 1
}

echo "==> Assemble $APP"
mkdir -p "$OUT_DIR"
if [ -e "$APP" ]; then
    PREVIOUS="$OUT_DIR/.previous-flashCat-$(date +%s).app"
    mv "$APP" "$PREVIOUS"
    for old in "$OUT_DIR"/.previous-flashCat-*.app; do
        [ -e "$old" ] || continue
        [ "$old" = "$PREVIOUS" ] && continue
        rm -rf "$old"
    done
fi
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp "$BINARY" "$APP/Contents/MacOS/flashCat"
chmod +x "$APP/Contents/MacOS/flashCat"

echo "==> Embed engine packs ($EMBED_PACKS)"
# APFS clones make the copy free: `cp -Rc` shares extents with vendor/engines, so
# the bundle is independent but only costs disk once.
if [ -d "$ROOT/vendor/engines" ] || [ -L "$ROOT/vendor/engines" ]; then
    rm -rf "$APP/Contents/Resources/engines"
    if [ "$EMBED_PACKS" = "link" ]; then
        ln -sfn "$ROOT/vendor/engines" "$APP/Contents/Resources/engines"
        echo "    symlinked (dev only): $ROOT/vendor/engines"
    else
        mkdir -p "$APP/Contents/Resources/engines"
        for engine in "$ROOT"/vendor/engines/*/; do
            name="$(basename "$engine")"
            cp -Rc "$engine" "$APP/Contents/Resources/engines/$name" \
                || cp -R "$engine" "$APP/Contents/Resources/engines/$name"
        done
        echo "    copied: $(ls "$APP/Contents/Resources/engines" | tr '\n' ' ')"
    fi
else
    echo "    (vendor/engines missing — run scripts/engines/build-omlx-pack.sh)"
fi

echo "==> Embed pack index"
# The app resolves releases through FLASHCAT_PACK_INDEX_URL first, then this
# bundled index. It is generated by scripts/engines/make-pack-index.sh.
if [ -f "$ROOT/pack-index.json" ]; then
    cp "$ROOT/pack-index.json" "$APP/Contents/Resources/pack-index.json"
    echo "     pack-index.json"
else
    echo "    (no pack-index.json — the app will fall back to local packs only)"
fi

echo "==> App icon"
# Single master artwork: Sources/FlashCat/Resources/app-icon.png. The same PNG is
# embedded for the in-app brand mark and rasterised into AppIcon.icns, so the
# Dock, Finder and the window chrome can never drift apart.
MASTER_ICON="$NATIVE_DIR/Sources/FlashCat/Resources/app-icon.png"
ICONSET="$OUT_DIR/AppIcon.iconset"
ICNS="$APP/Contents/Resources/AppIcon.icns"
rm -rf "$ICONSET"
mkdir -p "$ICONSET"

iconset_from_png() {
    local master="$1" iconset="$2" base retina
    for base in 16 32 128 256 512; do
        retina=$((base * 2))
        sips -z "$base" "$base" "$master" --out "$iconset/icon_${base}x${base}.png" >/dev/null 2>&1 || return 1
        sips -z "$retina" "$retina" "$master" --out "$iconset/icon_${base}x${base}@2x.png" >/dev/null 2>&1 || return 1
    done
}

if [ -f "$MASTER_ICON" ] && iconset_from_png "$MASTER_ICON" "$ICONSET" \
    && iconutil -c icns "$ICONSET" -o "$ICNS"; then
    cp "$MASTER_ICON" "$APP/Contents/Resources/app-icon.png"
    cp "$MASTER_ICON" "$OUT_DIR/app-icon.png"
    echo "     AppIcon.icns  <-  Sources/FlashCat/Resources/app-icon.png"
else
    echo "warning: $MASTER_ICON missing; falling back to the rendered icon" >&2
    PYTHON=""
    for candidate in python3; do
        if command -v "$candidate" >/dev/null 2>&1 && "$candidate" -c 'import PIL, numpy' >/dev/null 2>&1; then
            PYTHON="$candidate"
            break
        fi
    done
    if [ -n "$PYTHON" ] && "$PYTHON" "$ROOT/scripts/make-icon.py" "$ICONSET" >/dev/null 2>&1 \
        && iconutil -c icns "$ICONSET" -o "$ICNS"; then
        echo "     AppIcon.icns  <-  scripts/make-icon.py"
    else
        echo "warning: icon generation failed; the app will use the default icon" >&2
    fi
fi

# SwiftPM parks the brand artwork in FlashCat_FlashCat.bundle next to the
# executable; BrandMark looks it up in Contents/Resources first.
RESOURCE_BUNDLE="$NATIVE_DIR/.build/release/FlashCat_FlashCat.bundle"
if [ -d "$RESOURCE_BUNDLE" ]; then
    rm -rf "$APP/Contents/Resources/$(basename "$RESOURCE_BUNDLE")"
    cp -R "$RESOURCE_BUNDLE" "$APP/Contents/Resources/"
    echo "     $(basename "$RESOURCE_BUNDLE")"
else
    echo "warning: $RESOURCE_BUNDLE missing; the brand mark falls back to the app icon" >&2
fi

echo "==> Write Info.plist"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>zh_CN</string>
    <key>CFBundleDisplayName</key>
    <string>flashCat</string>
    <key>CFBundleExecutable</key>
    <string>flashCat</string>
    <key>CFBundleIdentifier</key>
    <string>$IDENTIFIER</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>flashCat</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$BUILD_NUMBER</string>
    <key>LSMinimumSystemVersion</key>
    <string>$MIN_MACOS</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSAppTransportSecurity</key>
    <dict>
        <key>NSAllowsLocalNetworking</key>
        <true/>
    </dict>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.developer-tools</string>
    <key>NSHumanReadableCopyright</key>
    <string>本地推理控制台</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
</dict>
</plist>
PLIST
plutil -lint "$APP/Contents/Info.plist" >/dev/null

echo "==> Ad-hoc sign"
if codesign --force --deep --sign - "$APP" >/dev/null 2>&1; then
    if codesign --verify --deep --strict "$APP" >/dev/null 2>&1; then
        echo "     signature verified"
    fi
else
    echo "warning: ad-hoc signing failed" >&2
fi

SIZE="$(du -sh "$APP" | cut -f1)"
echo "==> Built $APP ($SIZE)"

echo "==> Installers"
VERSION="$VERSION" BUILD_NUMBER="$BUILD_NUMBER" "$ROOT/scripts/make-installer.sh" "$APP"

if [ "$INSTALL" = "1" ]; then
    echo "==> Install to /Applications"
    "$ROOT/scripts/install-app.sh" "$APP"
    STAGED="$OUT_DIR/.build/flashCat.app"
    mkdir -p "$OUT_DIR/.build"
    rm -rf "$STAGED"
    mv "$APP" "$STAGED"
    echo "    Staging bundle moved to $STAGED (dev copy only)."
    echo "    Use the installed app:  open /Applications/flashCat.app"
    echo "    Do not run both copies at once; that is what leaves port 8000 taken."
else
    echo "    INSTALL=0: not installed. Open it with: open \"$APP\""
fi
